export const LANGS = [
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'fr', label: 'Français', dir: 'ltr' },
  { code: 'en', label: 'English', dir: 'ltr' },
];

let current = 'ar';

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (DICT[lang]) current = lang;
  return current;
}

export function dirLang(lang = current) {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

/** يترجم مفتاحاً إلى اللغة الحالية مع الرجوع للعربية ثم المفتاح نفسه. */
export function t(key) {
  return DICT[current]?.[key] ?? DICT.ar[key] ?? key;
}

/** يترجم اسم اليوم حسب اللغة الحالية باستعمال ترجمات الدليل إن توفّرت. */
export function dayName(day, guide) {
  if (!day) return '';
  if (current === 'ar') return day;
  const idx = (guide?.days || []).indexOf(day);
  const list = guide?.day_translations?.[current];
  if (idx >= 0 && Array.isArray(list) && list[idx]) return list[idx];
  return day;
}

/** يختار نصاً متعدد اللغات من كائن {ar,fr,en}. */
export function pick(value, fallback = '') {
  if (value == null) return fallback;
  if (typeof value === 'string') return value;
  return value[current] || value.ar || value.fr || value.en || fallback;
}
