-- ---------------------------------------------------------------------------
-- 1) جدول المسؤولين (admins) — هو الحارس الحقيقي للوحة التحكم
-- ---------------------------------------------------------------------------
create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text,
  created_at timestamptz not null default now()
);

alter table public.admins enable row level security;

-- كل مستعمل يشوف غير سطرو هو (كفاية باش نعرفو واش هو مسؤول)
drop policy if exists "admins_read_self" on public.admins;
create policy "admins_read_self" on public.admins
  for select to authenticated
  using (user_id = auth.uid());

-- دالة مساعدة: واش المستعمل الحالي مسؤول؟
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;

grant execute on function public.is_admin() to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 2) الإعلانات (announcements)
-- ---------------------------------------------------------------------------
create table if not exists public.announcements (
  id         bigint generated by default as identity primary key,
  title      text not null,
  body       text not null,
  kind       text not null default 'info'
             check (kind in ('info','warning','urgent','event')),
  status     text not null default 'draft'
             check (status in ('published','draft','archived')),
  starts_at  timestamptz,
  ends_at    timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_announcements_status
  on public.announcements (status, updated_at desc);

alter table public.announcements enable row level security;

-- قراءة عمومية للمنشور فقط
drop policy if exists "ann_read_published" on public.announcements;
create policy "ann_read_published" on public.announcements
  for select to anon, authenticated
  using (status = 'published');

-- المسؤولون: قراءة كل شيء
drop policy if exists "ann_admin_read" on public.announcements;
create policy "ann_admin_read" on public.announcements
  for select to authenticated
  using (public.is_admin());

-- المسؤولون: إضافة/تعديل/حذف
drop policy if exists "ann_admin_write" on public.announcements;
create policy "ann_admin_write" on public.announcements
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- ---------------------------------------------------------------------------
-- 3) ملفات الامتحانات (exam_files)
-- ---------------------------------------------------------------------------
create table if not exists public.exam_files (
  id               bigint generated by default as identity primary key,
  subject_id       text not null,
  exam_type        text not null default 'exam'
                   check (exam_type in ('exam','assignment')),
  year             integer,
  session          text not null default 'normal'
                   check (session in ('normal','makeup')),
  has_correction   boolean not null default false,
  file_path        text not null,
  correction_path  text,
  status           text not null default 'pending'
                   check (status in ('pending','approved','rejected')),
  contributor_name text,
  downloads        integer not null default 0,
  created_at       timestamptz not null default now()
);

create index if not exists idx_exam_files_status
  on public.exam_files (status, year desc, created_at desc);
create index if not exists idx_exam_files_subject
  on public.exam_files (subject_id);

alter table public.exam_files enable row level security;

-- قراءة عمومية للموافق عليه فقط
drop policy if exists "ef_read_approved" on public.exam_files;
create policy "ef_read_approved" on public.exam_files
  for select to anon, authenticated
  using (status = 'approved');

-- الزوار: يقترحو ملف (pending فقط) — ما يقدروش يوافقو على راسهم
drop policy if exists "ef_insert_pending" on public.exam_files;
create policy "ef_insert_pending" on public.exam_files
  for insert to anon, authenticated
  with check (status = 'pending' and downloads = 0);

-- المسؤول: كل الصلاحيات
drop policy if exists "ef_admin" on public.exam_files;
create policy "ef_admin" on public.exam_files
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- عدّاد التحميلات: دالة تتجاوز RLS (الزائر يقدر يزيد العدّاد فقط)
create or replace function public.bump_exam_download(exam_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
  update public.exam_files
     set downloads = downloads + 1
   where id = exam_id
     and status = 'approved';
$$;

grant execute on function public.bump_exam_download(bigint) to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 4) التخزين: حاوية edu-files (خاصة — الوصول عبر روابط مؤقتة)
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('edu-files', 'edu-files', false)
on conflict (id) do nothing;

-- قراءة الكائنات (ضرورية لتوليد الروابط المؤقتة) — الملفات تبقى خاصة
drop policy if exists "edu_files_read" on storage.objects;
create policy "edu_files_read" on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'edu-files');

-- الزوار: رفع فقط داخل المجلد contrib/
drop policy if exists "edu_files_insert_contrib" on storage.objects;
create policy "edu_files_insert_contrib" on storage.objects
  for insert to anon, authenticated
  with check (
    bucket_id = 'edu-files'
    and (storage.foldername(name))[1] = 'contrib'
  );

-- المسؤول: رفع/استبدال في أي مكان داخل edu-files
drop policy if exists "edu_files_admin_insert" on storage.objects;
create policy "edu_files_admin_insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'edu-files' and public.is_admin());

drop policy if exists "edu_files_admin_update" on storage.objects;
create policy "edu_files_admin_update" on storage.objects
  for update to authenticated
  using (bucket_id = 'edu-files' and public.is_admin());

-- المسؤول: حذف ملفات edu-files
drop policy if exists "edu_files_admin_delete" on storage.objects;
create policy "edu_files_admin_delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'edu-files' and public.is_admin());

