#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// Self-host the Arabic + Latin UI fonts so the PWA needs no third-party font
// request at runtime and avoids a render-blocking cross-origin round trip.
//
// Downloads the needed woff2 subsets from Google Fonts into web/assets/fonts
// and writes web/assets/fonts/fonts.css with relative URLs.
//
// Run:  node scripts/fetch-fonts.mjs
// ─────────────────────────────────────────────────────────────────────────────
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'web', 'assets', 'fonts');
// Start clean so renamed/deduped files don't linger.
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

// Only keep the subsets we actually need.
const KEEP_LABELS = new Set(['arabic', 'latin']);

const requests = [
  { family: 'IBM Plex Sans Arabic', param: 'IBM+Plex+Sans+Arabic', weights: [400, 600, 700] },
  { family: 'Inter', param: 'Inter', weights: [400, 600, 700] }
];

function labelFromRange(range) {
  const r = range || '';
  if (/U\+0600/.test(r)) return 'arabic';
  if (/U\+0000-00FF/.test(r)) return 'latin';
  return 'other';
}

async function css(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`CSS fetch failed ${res.status}`);
  return res.text();
}

const blocks = [];

for (const req of requests) {
  const url =
    `https://fonts.googleapis.com/css2?family=${req.param}:wght@${req.weights.join(';')}&display=swap`;
  const text = await css(url);
  // Split into @font-face blocks; each is preceded by a /* subset */ comment.
  const parts = text.split('/*').slice(1);
  for (const part of parts) {
    const label = part.slice(0, part.indexOf('*/')).trim();
    const face = part.slice(part.indexOf('*/') + 2);
    if (!face.includes('@font-face')) continue;
    if (!KEEP_LABELS.has(label)) continue;
    const weight = (face.match(/font-weight:\s*(\d+)/) || [])[1] || '400';
    const src = (face.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    const range = (face.match(/unicode-range:\s*([^;]+);/) || [])[1] || '';
    if (!src) continue;
    blocks.push({ family: req.family, weight, label, src, range });
  }
}

const lines = [
  '/* Self-hosted UI fonts — generated by scripts/fetch-fonts.mjs. Do not edit by hand. */'
];

let downloaded = 0;
const byHash = new Map(); // sha256 -> filename (dedupe variable fonts served once)
const grouped = new Map(); // family|subset|file -> { family, weightMin, weightMax, range }
for (const b of blocks) {
  const slug = b.family.toLowerCase().replace(/\s+/g, '-');
  const buf = Buffer.from(await (await fetch(b.src, { headers: { 'User-Agent': UA } })).arrayBuffer());
  const hash = crypto.createHash('sha256').update(buf).digest('hex');
  let file = byHash.get(hash);
  if (!file) {
    file = `${slug}-${b.weight}-${b.label}.woff2`;
    fs.writeFileSync(path.join(OUT, file), buf);
    byHash.set(hash, file);
    downloaded++;
  }
  const key = `${b.family}|${b.label}|${file}`;
  const g = grouped.get(key) || { family: b.family, file, weightMin: Infinity, weightMax: -Infinity, range: b.range.trim() };
  const w = Number(b.weight);
  g.weightMin = Math.min(g.weightMin, w);
  g.weightMax = Math.max(g.weightMax, w);
  grouped.set(key, g);
}

for (const g of grouped.values()) {
  const weight = g.weightMin === g.weightMax ? `${g.weightMin}` : `${g.weightMin} ${g.weightMax}`;
  lines.push(
    `@font-face{font-family:'${g.family}';font-style:normal;font-weight:${weight};font-display:swap;` +
      `src:url('./${g.file}') format('woff2');unicode-range:${g.range};}`
  );
}

fs.writeFileSync(path.join(OUT, 'fonts.css'), lines.join('\n') + '\n');
console.log(`Wrote ${downloaded} woff2 files + fonts.css to ${path.relative(ROOT, OUT)}`);
