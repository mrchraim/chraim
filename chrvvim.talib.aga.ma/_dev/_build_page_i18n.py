#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
_build_page_i18n.py — build ../page-i18n.js from the _dev/page_i18n_*.json sources.

Each source entry is {ar, fr, en, 'zgh-latn'}; the Tifinagh ("zgh") value is
transliterated from the Latin draft with the SAME rules used by _add_amazigh.py
({{...}} kept verbatim, tags/digits/emoji untouched, geminates collapsed).

Run:  python _build_page_i18n.py
Writes:  ../page-i18n.js   (UTF-8, no BOM — same as app.js / subjects.js)
"""
import json, os, glob, io

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT  = os.path.join(ROOT, "page-i18n.js")

# ---------------------------------------------------------------- transliteration
TIF = {
    'a':'ⴰ','b':'ⴱ','c':'ⴽ','d':'ⴷ','ḍ':'ⴹ','e':'ⴻ','f':'ⴼ','g':'ⴳ','ɣ':'ⵖ','γ':'ⵖ',
    'h':'ⵀ','ḥ':'ⵃ','i':'ⵉ','j':'ⵊ','k':'ⴽ','l':'ⵍ','m':'ⵎ','n':'ⵏ','o':'ⵓ','p':'ⴱ',
    'q':'ⵇ','r':'ⵔ','ṛ':'ⵕ','s':'ⵙ','ṣ':'ⵚ','š':'ⵛ','t':'ⵜ','ṭ':'ⵟ','u':'ⵓ','v':'ⴼ',
    'w':'ⵡ','x':'ⵅ','y':'ⵢ','z':'ⵣ','ẓ':'ⵥ','ɛ':'ⵄ','ʕ':'ⵄ','ʷ':'ⵯ','č':'ⵞ',
}

def _is_upper_ascii(ch):
    return 'A' <= ch <= 'Z'

def to_tifinagh(text):
    out, prev = [], None
    def push(tok, is_tif):
        nonlocal prev
        if is_tif and prev == tok:
            return
        out.append(tok)
        prev = tok if is_tif else None
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if text.startswith('{{', i):
            j = text.find('}}', i + 2)
            if j == -1:
                push(text[i:], False); break
            push(text[i+2:j], False); i = j + 2; continue
        if ch == '{':
            j = text.find('}', i)
            if j != -1:
                push(text[i:j+1], False); i = j + 1; continue
        if ch == '<':
            j = text.find('>', i)
            if j != -1:
                push(text[i:j+1], False); i = j + 1; continue
        if _is_upper_ascii(ch):
            j = i
            while j < n and _is_upper_ascii(text[j]):
                j += 1
            if j - i >= 2:
                push(text[i:j], False); i = j; continue
        low = ch.lower()
        if low in TIF:
            push(TIF[low], True)
        else:
            push(ch, False)
        i += 1
    return ''.join(out)

def to_latin(text):
    import re
    return re.sub(r'\{\{(.*?)\}\}', r'\1', text)

# ---------------------------------------------------------------- build
def main():
    merged = {}
    for path in sorted(glob.glob(os.path.join(HERE, "page_i18n_*.json"))):
        with io.open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        for k, v in data.items():
            if k in merged:
                raise SystemExit("duplicate key: " + k)
            merged[k] = v

    out = {}
    for k, v in merged.items():
        lat = v.get("zgh-latn")
        if lat is None:
            raise SystemExit("missing zgh-latn for: " + k)
        out[k] = {
            "ar": v.get("ar", ""),
            "fr": v.get("fr", ""),
            "en": v.get("en", ""),
            "zgh": to_tifinagh(lat),
            "zgh-latn": to_latin(lat),
        }

    head = (
        "/* CHRVVIM Campus \u2014 first-page i18n (hub, tools, sections, footer).\n"
        "   GENERATED by _dev/_build_page_i18n.py \u2014 do not edit by hand.\n"
        "   Source dictionaries: _dev/page_i18n_*.json (ar/fr/en + Amazigh Latin);\n"
        "   the Tifinagh (\"zgh\") values are transliterated automatically.\n"
        "   Exposes window.CHRVVIM_PAGE = { t(key), apply(lang), lang(), LANGS, dict }. */\n"
    )
    tail = """
  return { t:t, apply:apply, lang:lang, LANGS:LANGS, dict:D };
})();
"""
    js = head + "window.CHRVVIM_PAGE=(function(){\n  \"use strict\";\n"
    js += "  var D=" + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
    js += """
  var LANGS=["ar","fr","en","zgh","zgh-latn"];
  var SPEC={"\\u0627\\u0644\\u0645\\u0647\\u0646 \\u0627\\u0644\\u0642\\u0627\\u0646\\u0648\\u0646\\u064a\\u0629 \\u0648\\u0627\\u0644\\u0642\\u0636\\u0627\\u0626\\u064a\\u0629":"wa.spec.legal","\\u0642\\u0627\\u0646\\u0648\\u0646 \\u0627\\u0644\\u0645\\u0627\\u0644 \\u0648\\u0627\\u0644\\u0623\\u0639\\u0645\\u0627\\u0644":"wa.spec.business","\\u0627\\u0644\\u0642\\u0627\\u0646\\u0648\\u0646 \\u0627\\u0644\\u0645\\u062f\\u0646\\u064a \\u0648\\u0627\\u0644\\u0639\\u0642\\u0627\\u0631\\u064a":"wa.spec.civil","\\u0627\\u0644\\u0642\\u0627\\u0646\\u0648\\u0646 \\u0627\\u0644\\u062c\\u0646\\u0627\\u0626\\u064a \\u0648\\u0627\\u0644\\u0639\\u0644\\u0648\\u0645 \\u0627\\u0644\\u0623\\u0645\\u0646\\u064a\\u0629":"wa.spec.criminal"};
  function lang(){
    try{ var l=localStorage.getItem("cc_uilang")||"ar"; return LANGS.indexOf(l)<0?"ar":l; }catch(e){ return "ar"; }
  }
  function t(k,l){
    var e=D[k]; if(!e) return k;
    var v=e[l||lang()]; if(v==null) v=e.ar; return v==null?"":v;
  }
  function fillEls(l){
    document.querySelectorAll("[data-i18n],[data-i18n-html]").forEach(function(el){
      var k=el.getAttribute("data-i18n")||el.getAttribute("data-i18n-html");
      var v=t(k,l);
      if(el.hasAttribute("data-i18n-html")) el.innerHTML=v; else el.textContent=v;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function(el){ el.setAttribute("placeholder",t(el.getAttribute("data-i18n-ph"),l)); });
    document.querySelectorAll("[data-i18n-aria]").forEach(function(el){ el.setAttribute("aria-label",t(el.getAttribute("data-i18n-aria"),l)); });
    document.querySelectorAll("[data-i18n-title]").forEach(function(el){ el.setAttribute("title",t(el.getAttribute("data-i18n-title"),l)); });
  }
  function waCards(l){
    var wa=document.getElementById("student-wa-groups"); if(!wa) return;
    wa.setAttribute("dir", (l==="ar")?"rtl":"ltr");
    wa.querySelectorAll(".wa-group").forEach(function(card){
      var st=card.querySelector("strong"); if(!st) return;
      var orig=st.getAttribute("data-o"); if(orig===null){ orig=st.textContent.trim(); st.setAttribute("data-o",orig); }
      var body=orig.replace(/^\\s*\\u0627\\u0644\\u0634\\u0639\\u0628\\u0629\\s*/,"");
      var parts=body.split("\\u2014");
      var letter=(parts.shift()||"").trim();
      var label=t("wa.sec",l)+" "+letter;
      if(parts.length){ var spec=parts.join("\\u2014").trim(); label+=" \\u2014 "+(SPEC[spec]?t(SPEC[spec],l):spec); }
      st.textContent=label;
      var sm=card.querySelector("small");
      if(sm){ sm.textContent=t("wa.small",l).replace("{s}",card.getAttribute("data-sem")||""); }
      var a=card.querySelector(".wa-join");
      if(a){ a.textContent=t("wa.join",l); a.setAttribute("aria-label",t("wa.join",l)+" \\u2014 "+letter); }
    });
  }
  function apply(l){
    l=l||lang();
    fillEls(l);
    waCards(l);
    var lc=document.getElementById("legalCard"); if(lc) lc.setAttribute("dir",(l==="ar")?"rtl":"ltr");
    document.dispatchEvent(new CustomEvent("cc:lang",{detail:{lang:l}}));
  }
"""
    js += tail

    raw = js.encode("utf-8")
    with open(OUT, "wb") as f:
        f.write(raw)
    print("wrote", OUT, "keys:", len(out), "bytes:", len(raw))

if __name__ == "__main__":
    main()
